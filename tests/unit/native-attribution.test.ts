async function fixture() {
  const root = await mkdtemp(join(tmpdir(), "openfilm-attribution-"));
  roots.push(root);
  await mkdir(
    join(root, "node_modules/.pnpm/included@1.0.0/node_modules/included"),
    { recursive: true },
  );
  const pkg = "node_modules/.pnpm/included@1.0.0/node_modules/included";
  await writeFile(
    join(root, "package.json"),
    '{"name":"openfilm","version":"1.0.0","license":"Apache-2.0"}',
  );
  await writeFile(
    join(root, "pnpm-lock.yaml"),
    "lockfileVersion: '9.0'\npackages:\n  included@1.0.0:\n    resolution: {integrity: sha512-aW5jbHVkZWQ=}\n  unshipped@1.0.0:\n    resolution: {integrity: sha512-dW5zaGlwcGVk}\nsnapshots: {}\n",
  );
  await writeFile(
    join(root, pkg, "package.json"),
    '{"name":"included","version":"1.0.0","license":"MIT"}',
  );
  await writeFile(join(root, pkg, "index.js"), "export const answer=42;");
  await writeFile(
    join(root, "entry.js"),
    `import {answer} from './${pkg}/index.js'; console.log(answer);`,
  );
  const result = await build({
    entryPoints: [join(root, "entry.js")],
    outfile: join(root, "dist/server/index.mjs"),
    bundle: true,
    format: "esm",
    metafile: true,
    absWorkingDir: root,
  });
  const outputs = Object.entries(result.metafile!.outputs).map(
    ([path, data]) => ({
      path,
      delivery: "service" as const,
      inputs: Object.entries(data.inputs).map(([path, input]) => ({
        path,
        bytesInOutput: input.bytesInOutput,
      })),
    }),
  );
  return { root, pkg, outputs, metafile: result.metafile! };
}
/** Exact installed entry/manifest/notices, with every generated byte private. */
async function generatedRuntimeFixture(
  owner: "esbuild" | "@vitejs/plugin-vue",
) {
  const repository = await mkdtemp(
    join(tmpdir(), "openfilm-generated-attribution-"),
  );
  roots.push(repository);
  for (const path of ["package.json", "pnpm-lock.yaml"])
    await copyFile(resolve(path), join(repository, path));
  const originalEntry = await realpath(
    createRequire(resolve("package.json")).resolve(owner),
  );
  let packageRoot = dirname(originalEntry);
  for (;;) {
    try {
      const data = JSON.parse(
        await readFile(join(packageRoot, "package.json"), "utf8"),
      );
      if (data.name === owner) break;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    const parent = dirname(packageRoot);
    if (parent === packageRoot)
      throw new Error("Frozen helper package missing");
    packageRoot = parent;
  }
  const files = [
    "package.json",
    relative(packageRoot, originalEntry),
    ...(await readdir(packageRoot, { withFileTypes: true }))
      .filter(
        (file) =>
          file.isFile() &&
          /^(?:licen[cs]e|copying|notice|copyright)(?:[.-].*)?$/iu.test(
            file.name,
          ),
      )
      .map((file) => file.name),
  ];
  for (const path of new Set(files)) {
    const destination = join(repository, "node_modules", owner, path);
    await mkdir(dirname(destination), { recursive: true });
    await copyFile(join(packageRoot, path), destination);
  }
  await mkdir(join(repository, "dist"));
  return repository;
}
